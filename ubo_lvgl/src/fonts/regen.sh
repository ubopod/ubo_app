  echo "generating ubo_icon_$size.c"
  # shellcheck disable=SC2086
  npx lv_font_conv \
    --font "$FONT" \
    --size "$size" --bpp 4 --format lvgl --no-compress \
    $RANGES \
    -o "ubo_icon_$size.c"
done
