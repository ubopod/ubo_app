# Regenerate the compiled-in icon fonts (`ubo_icon_<size>.c`) from
# ../../assets/fonts/ArimoNerdFont-Regular.ttf — the same Nerd Font `ubo_gui`
# uses. Only the codepoints listed below are embedded; anything else renders
# blank on targets that cannot load the full `assets/ubo_icons_*.bin` at
# runtime (i.e. the ESP32 firmware). Add a codepoint here whenever a service
# starts emitting an icon the ESP32 must show.
#
# Requires lv_font_conv (`npm install lv_font_conv`); `--no-compress` is
